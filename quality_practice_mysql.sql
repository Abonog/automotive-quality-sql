-- Quality Practice Database (MySQL version)
-- Suppliers -> Parts -> Production Batches -> Inspections -> Defects

CREATE DATABASE IF NOT EXISTS quality_practice;
USE quality_practice;

DROP TABLE IF EXISTS defects;
DROP TABLE IF EXISTS inspections;
DROP TABLE IF EXISTS production_batches;
DROP TABLE IF EXISTS parts;
DROP TABLE IF EXISTS suppliers;

CREATE TABLE suppliers (
    supplier_id INT PRIMARY KEY,
    supplier_name VARCHAR(100) NOT NULL,
    country VARCHAR(50) NOT NULL,
    tier VARCHAR(20) NOT NULL
);

CREATE TABLE parts (
    part_id INT PRIMARY KEY,
    part_name VARCHAR(100) NOT NULL,
    category VARCHAR(50) NOT NULL,
    supplier_id INT NOT NULL,
    FOREIGN KEY (supplier_id) REFERENCES suppliers(supplier_id)
);

CREATE TABLE production_batches (
    batch_id INT PRIMARY KEY,
    part_id INT NOT NULL,
    plant VARCHAR(50) NOT NULL,
    production_date DATE NOT NULL,
    quantity_produced INT NOT NULL,
    FOREIGN KEY (part_id) REFERENCES parts(part_id)
);

CREATE TABLE inspections (
    inspection_id INT PRIMARY KEY,
    batch_id INT NOT NULL,
    inspection_date DATE NOT NULL,
    inspector VARCHAR(50) NOT NULL,
    result VARCHAR(10) NOT NULL,
    FOREIGN KEY (batch_id) REFERENCES production_batches(batch_id)
);

CREATE TABLE defects (
    defect_id INT PRIMARY KEY,
    inspection_id INT NOT NULL,
    defect_type VARCHAR(50) NOT NULL,
    severity VARCHAR(20) NOT NULL,
    quantity INT NOT NULL,
    FOREIGN KEY (inspection_id) REFERENCES inspections(inspection_id)
);


